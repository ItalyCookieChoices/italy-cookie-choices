<?php

declare(strict_types=1);

namespace ItalyCookieChoices\Integrations\UI;

use ItalyCookieChoices\Consent\UI\ConsentScript;
use ItalyCookieChoices\Integrations\Application\ConsentModeMapping;
use ItalyCookieChoices\Integrations\Application\IntegrationSettings;
use ItalyStrap\Asset\AssetLoader;
use ItalyStrap\Asset\BuildMetadata;
use ItalyStrap\Asset\BuildMetadataFile;
use ItalyStrap\Asset\EventName;
use ItalyStrap\Asset\Handle;
use ItalyStrap\Asset\InlineScript;
use ItalyStrap\Asset\Position;
use ItalyStrap\Asset\RegisterOnly;
use ItalyStrap\Asset\Script;
use ItalyStrap\Asset\ScriptLoader;
use ItalyStrap\Event\SubscriberInterface;
use SplFileInfo;

/**
 * Prints the Google Consent Mode v2 script at the start of the head, before the Google tags.
 *
 * Every consent type is denied by default, the stored consent and each change update the granted ones.
 * The script is only registered, then printed right after wp_enqueue_scripts,
 * so it runs before the tags of the theme and of the other plugins.
 */
final readonly class ConsentModeScript implements SubscriberInterface
{
    /**
     * WordPress prints it with the id italy-cookie-choices-consent-mode-js.
     */
    public const HANDLE = 'italy-cookie-choices-consent-mode';

    private const SCRIPT = 'consent-mode.js';

    // After wp_enqueue_scripts, at wp_head priority 1, and before the scripts of the head, at 9.
    private const START_OF_THE_HEAD = 2;

    /**
     * How long the Google tags wait for the update of the stored consent, in milliseconds.
     */
    private const WAIT_FOR_UPDATE = 500;

    /**
     * @param string $buildPath The assets/build folder, with the trailing slash.
     * @param string $buildUrl The assets/build URL, with the trailing slash.
     */
    public function __construct(
        private IntegrationSettings $settings,
        private ConsentModeMapping $mapping,
        private ConsentScript $consent,
        private AssetLoader $assets,
        private ScriptLoader $scripts,
        private string $buildPath,
        private string $buildUrl,
    ) {
    }

    public function getSubscribedEvents(): iterable
    {
        yield EventName::FRONT_END => 'enqueue';
        yield 'wp_head' => [
            self::CALLBACK => 'print',
            self::PRIORITY => self::START_OF_THE_HEAD,
        ];
    }

    public function enqueue(): void
    {
        $metadata = $this->metadata();
        if ($metadata === null || !$this->settings->sendsConsentMode()) {
            return;
        }

        $this->assets->load(new Script(
            handle: new Handle(self::HANDLE),
            source: $this->buildUrl . self::SCRIPT,
            dependencies: $metadata->dependencies(),
            version: $metadata->version(),
            inlineScripts: [new InlineScript(
                \sprintf('window.italyCookieChoicesConsentMode = %s;', (string) \wp_json_encode($this->config())),
                Position::Before
            )],
            condition: new RegisterOnly(),
        ));
    }

    /**
     * Prints the script with its configuration, when it is registered.
     */
    public function print(): void
    {
        $this->scripts->print(new Handle(self::HANDLE));
    }

    /**
     * @return array{consent: array<string, mixed>, mapping: array<string, list<string>>, waitForUpdate: int}
     */
    public function config(): array
    {
        return [
            'consent' => $this->consent->config(),
            'mapping' => $this->mapping->toArray(),
            'waitForUpdate' => self::WAIT_FOR_UPDATE,
        ];
    }

    /**
     * The dependencies and the version generated by the build, null when the assets are not built.
     */
    private function metadata(): ?BuildMetadata
    {
        $file = new BuildMetadataFile(new SplFileInfo($this->buildPath . self::SCRIPT));

        return $file->exists() ? $file->read() : null;
    }
}
