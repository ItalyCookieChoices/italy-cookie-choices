<?php

declare(strict_types=1);

namespace ItalyCookieChoices\Integrations\UI;

use ItalyCookieChoices\Consent\UI\ConsentScript;
use ItalyCookieChoices\Integrations\Application\WpConsentApiMapping;
use ItalyCookieChoices\Settings\Options;
use ItalyStrap\Event\SubscriberInterface;

/**
 * Loads the script that writes the consent to the WP Consent API, when the API is active and the banner is on.
 *
 * It runs in the footer after the script of the API, that defines wp_set_consent(), and after the consent API
 * of the plugin. The script is built from assets/src/wp-consent-api.
 */
final readonly class WpConsentApiScript implements SubscriberInterface
{
    public const HANDLE = 'italy-cookie-choices-wp-consent-api';

    /**
     * The script of the WP Consent API, registered late on wp_enqueue_scripts.
     */
    public const WP_CONSENT_API = 'wp-consent-api';

    private const SCRIPT = 'wp-consent-api.js';
    private const ASSET = 'wp-consent-api.asset.php';
    private const CONSENT_TYPE = 'optin';

    // The WP Consent API enqueues its script at PHP_INT_MAX - 100.
    private const AFTER_WP_CONSENT_API = \PHP_INT_MAX - 50;

    /**
     * @param string $buildPath The assets/build folder, with the trailing slash.
     * @param string $buildUrl The assets/build URL, with the trailing slash.
     */
    public function __construct(
        private Options $options,
        private WpConsentApiMapping $mapping,
        private string $buildPath,
        private string $buildUrl,
    ) {
    }

    public function getSubscribedEvents(): iterable
    {
        yield 'wp_enqueue_scripts' => [
            self::CALLBACK => 'enqueue',
            self::PRIORITY => self::AFTER_WP_CONSENT_API,
        ];
    }

    public function enqueue(): void
    {
        $asset = $this->asset();
        if ($asset === null || !$this->options->isActive() || !\wp_script_is(self::WP_CONSENT_API, 'registered')) {
            return;
        }

        \wp_enqueue_script(
            self::HANDLE,
            $this->buildUrl . self::SCRIPT,
            [...$asset['dependencies'], self::WP_CONSENT_API, ConsentScript::HANDLE],
            $asset['version'],
            ['in_footer' => true]
        );
        \wp_add_inline_script(
            self::HANDLE,
            \sprintf('window.italyCookieChoicesWpConsentApi = %s;', (string) \wp_json_encode($this->config())),
            'before'
        );
    }

    /**
     * @return array{consentType: string, mapping: array<string, list<string>>}
     */
    public function config(): array
    {
        return [
            'consentType' => self::CONSENT_TYPE,
            'mapping' => $this->mapping->toArray(),
        ];
    }

    /**
     * The dependencies and the version generated by the build, null when the assets are not built.
     *
     * @return array{dependencies: list<non-empty-string>, version: string}|null
     */
    private function asset(): ?array
    {
        $file = $this->buildPath . self::ASSET;
        if (!\is_readable($file)) {
            return null;
        }

        /** @var array{dependencies: list<non-empty-string>, version: string} */
        return require $file;
    }
}
