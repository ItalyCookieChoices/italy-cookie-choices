<?php

declare(strict_types=1);

namespace ItalyCookieChoices\ConsentLog\UI;

use ItalyCookieChoices\Consent\UI\ConsentScript;
use ItalyCookieChoices\ConsentLog\Application\LogSettings;
use ItalyStrap\Event\SubscriberInterface;

/**
 * Loads the script that sends each choice to the consent log, built from assets/src/consent-log.
 */
final readonly class LogScript implements SubscriberInterface
{
    public const HANDLE = 'italy-cookie-choices-consent-log';

    private const SCRIPT = 'consent-log.js';
    private const ASSET = 'consent-log.asset.php';

    /**
     * @param string $buildPath The assets/build folder, with the trailing slash.
     * @param string $buildUrl The assets/build URL, with the trailing slash.
     */
    public function __construct(
        private LogSettings $settings,
        private string $buildPath,
        private string $buildUrl,
    ) {
    }

    public function getSubscribedEvents(): iterable
    {
        yield 'wp_enqueue_scripts' => 'enqueue';
    }

    public function enqueue(): void
    {
        $asset = $this->asset();
        if ($asset === null || !$this->settings->isEnabled()) {
            return;
        }

        \wp_enqueue_script(
            self::HANDLE,
            $this->buildUrl . self::SCRIPT,
            [...$asset['dependencies'], ConsentScript::HANDLE],
            $asset['version'],
            ['in_footer' => true]
        );
        \wp_add_inline_script(
            self::HANDLE,
            \sprintf('window.italyCookieChoicesLog = %s;', (string) \wp_json_encode(['url' => $this->url()])),
            'before'
        );
    }

    public function url(): string
    {
        return \rest_url(ConsentLogEndpoint::NAMESPACE . ConsentLogEndpoint::ROUTE);
    }

    /**
     * The dependencies and the version generated by the build, null when the assets are not built.
     *
     * @return array{dependencies: list<non-empty-string>, version: string}|null
     */
    private function asset(): ?array
    {
        $file = $this->buildPath . self::ASSET;
        if (!\is_readable($file)) {
            return null;
        }

        /** @var array{dependencies: list<non-empty-string>, version: string} */
        return require $file;
    }
}
