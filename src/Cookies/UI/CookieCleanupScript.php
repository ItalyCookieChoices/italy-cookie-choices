<?php

declare(strict_types=1);

namespace ItalyCookieChoices\Cookies\UI;

use ItalyCookieChoices\Blocking\UI\BlockableRequest;
use ItalyCookieChoices\Consent\UI\ConsentScript;
use ItalyCookieChoices\Consent\UI\ConsentTexts;
use ItalyCookieChoices\Cookies\Application\CookieTableFactory;
use ItalyCookieChoices\Cookies\Domain\Cookie;
use ItalyStrap\Asset\AssetLoader;
use ItalyStrap\Asset\BuildMetadata;
use ItalyStrap\Asset\BuildMetadataFile;
use ItalyStrap\Asset\Dependencies;
use ItalyStrap\Asset\EventName;
use ItalyStrap\Asset\Handle;
use ItalyStrap\Asset\InlineScript;
use ItalyStrap\Asset\Position;
use ItalyStrap\Asset\Script;
use ItalyStrap\Asset\ScriptLoading;
use ItalyStrap\Event\SubscriberInterface;
use SplFileInfo;

/**
 * Loads the script that deletes the cookies of the categories without the consent, on load and after each choice.
 *
 * The names come from the cookie table, the necessary cookies are never deleted.
 * The script is built from assets/src/cookie-cleanup.
 */
final readonly class CookieCleanupScript implements SubscriberInterface
{
    public const HANDLE = 'italy-cookie-choices-cookie-cleanup';

    private const SCRIPT = 'cookie-cleanup.js';

    /**
     * @param string $buildPath The assets/build folder, with the trailing slash.
     * @param string $buildUrl The assets/build URL, with the trailing slash.
     */
    public function __construct(
        private CookieTableFactory $table,
        private ConsentTexts $texts,
        private BlockableRequest $request,
        private AssetLoader $assets,
        private string $buildPath,
        private string $buildUrl,
    ) {
    }

    public function getSubscribedEvents(): iterable
    {
        yield EventName::FRONT_END => 'enqueue';
    }

    public function enqueue(): void
    {
        $metadata = $this->metadata();
        if ($metadata === null || !$this->request->isBlockable()) {
            return;
        }

        $this->assets->load(new Script(
            handle: new Handle(self::HANDLE),
            source: $this->buildUrl . self::SCRIPT,
            dependencies: $metadata->dependencies()->with(new Dependencies(ConsentScript::HANDLE)),
            version: $metadata->version(),
            loading: new ScriptLoading(inFooter: true),
            inlineScripts: [new InlineScript(
                \sprintf('window.italyCookieChoicesCookieCleanup = %s;', (string) \wp_json_encode($this->config())),
                Position::Before
            )],
        ));
    }

    /**
     * The names of the cookies of each optional category, a name ending with * is a prefix.
     *
     * @return array{categories: array<string, list<string>>}
     */
    public function config(): array
    {
        $table = $this->table->create();

        $categories = [];
        foreach ($this->texts->all()['categories'] as $category) {
            $names = \array_map(
                static fn(Cookie $cookie): string => $cookie->name(),
                $table->inCategory($category['id'])
            );
            if ($category['required'] || $names === []) {
                continue;
            }

            $categories[$category['id']] = $names;
        }

        return ['categories' => $categories];
    }

    /**
     * The dependencies and the version generated by the build, null when the assets are not built.
     */
    private function metadata(): ?BuildMetadata
    {
        $file = new BuildMetadataFile(new SplFileInfo($this->buildPath . self::SCRIPT));

        return $file->exists() ? $file->read() : null;
    }
}
