<?php

declare(strict_types=1);

namespace ItalyCookieChoices\Migration\Infrastructure\Complianz;

/**
 * Reads the settings Complianz keeps in the database, also when it is deactivated.
 *
 * Complianz 7 keeps them in cmplz_options, the versions before in two options. The banner is the default row
 * of its table, some columns are serialized arrays: they are read without objects.
 */
final readonly class ComplianzStorage
{
    private const OPTIONS = 'cmplz_options';
    private const LEGACY_OPTIONS = ['complianz_options_wizard', 'complianz_options_settings'];
    private const SCRIPTS = 'complianz_options_custom-scripts';
    private const EXCLUDED_POSTS = 'cmplz_excluded_posts_array';
    private const BANNER_TABLE = 'cmplz_cookiebanners';
    private const BANNER_TABLE_VERSION = 'cmplz_cbdb_version';
    private const COOKIE_TABLE = 'cmplz_cookies';
    private const SERVICE_TABLE = 'cmplz_services';
    private const COOKIE_TABLE_VERSION = 'cmplz_cookietable_version';

    public function __construct(
        private \wpdb $database,
    ) {
    }

    public function hasSettings(): bool
    {
        return $this->options() !== [] || \get_option(self::BANNER_TABLE_VERSION) !== false;
    }

    /**
     * @return array<array-key, mixed>
     */
    public function options(): array
    {
        $options = \get_option(self::OPTIONS);
        if (\is_array($options)) {
            return $options;
        }

        $legacy = [];
        foreach (self::LEGACY_OPTIONS as $name) {
            $option = \get_option($name);
            $legacy = [...$legacy, ...(\is_array($option) ? $option : [])];
        }

        return $legacy;
    }

    /**
     * The default banner, or the first one, with the arrays unserialized.
     *
     * @return array<string, mixed>
     */
    public function banner(): array
    {
        if (\get_option(self::BANNER_TABLE_VERSION) === false) {
            return [];
        }

        $table = $this->database->prefix . self::BANNER_TABLE;
        // phpcs:ignore WordPress.DB.PreparedSQL.InterpolatedNotPrepared -- The name of a table of Complianz.
        $row = $this->database->get_row("SELECT * FROM $table ORDER BY `default` DESC, ID ASC LIMIT 1", \ARRAY_A);

        return \is_array($row) ? $this->columns(\array_map($this->unserialized(...), $row)) : [];
    }

    /**
     * The scripts of the script center: block_script, add_script and whitelist_script.
     *
     * @return array<array-key, mixed>
     */
    public function scripts(): array
    {
        $scripts = \get_option(self::SCRIPTS);

        return \is_array($scripts) ? $scripts : [];
    }

    /**
     * The slugs of the pages where the banner does not show.
     *
     * @return list<string>
     */
    public function excludedPosts(): array
    {
        $posts = \get_option(self::EXCLUDED_POSTS);

        return \array_values(\array_filter(\is_array($posts) ? $posts : [], \is_string(...)));
    }

    /**
     * The page of a document chosen as an existing page, like "cookie-statement" or "impressum".
     */
    public function documentPage(string $document): int
    {
        $page = \get_option('cmplz_' . $document . '_custom_page');

        return \is_numeric($page) ? (int) $page : 0;
    }

    /**
     * The published page with a document generated by Complianz, its shortcode or its block.
     */
    public function generatedDocumentPage(string $document): int
    {
        $page = $this->database->get_var($this->database->prepare(
            "SELECT ID FROM %i WHERE post_status = 'publish' AND post_type = 'page'
            AND (post_content LIKE %s OR post_content LIKE %s) ORDER BY ID ASC LIMIT 1",
            $this->database->posts,
            '%' . $this->database->esc_like('[cmplz-document type="' . $document . '"') . '%',
            '%' . $this->database->esc_like('"selectedDocument":"' . $document . '"') . '%'
        ));

        return \is_numeric($page) ? (int) $page : 0;
    }

    /**
     * The address of a document written by hand.
     */
    public function documentUrl(string $document): string
    {
        $url = \get_option('cmplz_' . $document . '_custom_page_url');

        return \is_string($url) ? $url : '';
    }

    /**
     * The cookies listed on the policy, not deleted, not ignored and not translations.
     *
     * @return list<array<string, mixed>>
     */
    public function cookies(): array
    {
        if (\get_option(self::COOKIE_TABLE_VERSION) === false) {
            return [];
        }

        $table = $this->database->prefix . self::COOKIE_TABLE;
        // phpcs:ignore WordPress.DB.PreparedSQL.InterpolatedNotPrepared -- The name of a table of Complianz.
        $rows = $this->database->get_results(
            "SELECT * FROM $table WHERE deleted = 0 AND ignored = 0 AND showOnPolicy = 1 AND isTranslationFrom = 0",
            \ARRAY_A
        );

        return \array_map($this->columns(...), $rows);
    }

    /**
     * The names of the services, by id.
     *
     * @return array<int, string>
     */
    public function serviceNames(): array
    {
        if (\get_option(self::COOKIE_TABLE_VERSION) === false) {
            return [];
        }

        $table = $this->database->prefix . self::SERVICE_TABLE;
        // phpcs:ignore WordPress.DB.PreparedSQL.InterpolatedNotPrepared -- The name of a table of Complianz.
        $rows = $this->database->get_results("SELECT ID, name FROM $table", \ARRAY_A);
        $names = [];
        foreach ($rows as $row) {
            if (!\is_numeric($row['ID'] ?? null) || !\is_string($row['name'] ?? null)) {
                continue;
            }

            $names[(int) $row['ID']] = $row['name'];
        }

        return $names;
    }

    /**
     * @param array<array-key, mixed> $row
     * @return array<string, mixed>
     */
    private function columns(array $row): array
    {
        $columns = [];
        foreach ($row as $name => $value) {
            $columns[(string) $name] = $value;
        }

        return $columns;
    }

    private function unserialized(mixed $value): mixed
    {
        if (!\is_string($value) || !\is_serialized($value)) {
            return $value;
        }

        // Only arrays: an object in a column is not created.
        $unserialized = @\unserialize($value, ['allowed_classes' => false]); // phpcs:ignore

        return \is_array($unserialized) ? $unserialized : $value;
    }
}
