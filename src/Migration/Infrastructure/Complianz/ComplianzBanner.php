<?php

declare(strict_types=1);

namespace ItalyCookieChoices\Migration\Infrastructure\Complianz;

use ItalyCookieChoices\Blocking\Application\BlockingSetting;
use ItalyCookieChoices\Consent\Application\ConsentSetting;
use ItalyCookieChoices\Consent\Domain\BannerLink;
use ItalyCookieChoices\Consent\Domain\Category;
use ItalyCookieChoices\Integrations\Application\IntegrationSetting;
use ItalyCookieChoices\Migration\Application\Conversions;
use ItalyCookieChoices\Settings\PluginSetting;

/**
 * The banner of Complianz and its general settings, in the shape of the settings of Cookie Choices.
 *
 * A setting Complianz leaves off keeps the default of Cookie Choices: the import turns features on, not off.
 */
final readonly class ComplianzBanner
{
    public const NAME = 'Complianz';

    private const YES = 'yes';

    /**
     * The positions of the banner of Complianz, as the positions of Cookie Choices.
     */
    private const POSITIONS = ['center' => '2', 'bottom' => '3', 'bottom-left' => '4', 'bottom-right' => '5'];

    /**
     * The answers to "Do you compile statistics" that load Google Analytics.
     */
    private const ANALYTICS = ['google-analytics', 'gtg'];

    /**
     * The documents of Complianz for the links of the banner.
     */
    private const DOCUMENTS = ['cookie-statement' => BannerLink::Policy, 'impressum' => BannerLink::LegalNotice];

    /**
     * The categories of Complianz: the columns of the label and of the description.
     */
    private const CATEGORIES = [
        Category::NECESSARY => ['category_functional', 'functional_text'],
        Category::PREFERENCES => ['category_prefs', 'preferences_text'],
        Category::STATISTICS => ['category_stats', 'statistics_text'],
        Category::MARKETING => ['category_all', 'marketing_text'],
    ];

    public function __construct(
        private ComplianzStorage $storage,
        private Conversions $conversions,
    ) {
    }

    /**
     * @return array<string, mixed>
     */
    public function settings(): array
    {
        $options = $this->storage->options();
        $banner = $this->storage->banner();

        return \array_filter(
            [
                ...$this->banner($options, $banner),
                ...$this->links($options),
                ...$this->behaviour($options),
                ...$this->integrations($options),
            ],
            static fn(mixed $value): bool => $value !== '' && $value !== []
        );
    }

    /**
     * @return list<string>
     */
    public function notes(): array
    {
        $options = $this->storage->options();
        $banner = $this->storage->banner();
        $notes = [];
        if ($this->isOn($banner, 'dismiss_on_scroll') || $this->isOn($banner, 'dismiss_on_timeout')) {
            $notes[] = \__(
                'The consent on scroll or after a time is not imported: it is not a valid consent.',
                'italy-cookie-choices'
            );
        }

        if (\array_diff($this->regions($options), ['eu']) !== []) {
            $notes[] = \__(
                'The regions and the banner for the United States are not imported: '
                . 'Cookie Choices asks the consent everywhere.',
                'italy-cookie-choices'
            );
        }

        if ($this->customCss($banner) !== '') {
            $notes[] = \__(
                'The custom CSS is imported in a comment: rewrite it for Cookie Choices.',
                'italy-cookie-choices'
            );
        }

        foreach (\array_keys(self::DOCUMENTS) as $document) {
            if (($options[$document] ?? '') === 'generated') {
                $notes[] = \__(
                    'A document generated by Complianz is linked as it is: '
                    . 'its content stops working without Complianz.',
                    'italy-cookie-choices'
                );
                break;
            }
        }

        return $notes;
    }

    /**
     * @param array<array-key, mixed> $options
     * @param array<string, mixed> $banner
     * @return array<string, mixed>
     */
    private function banner(array $options, array $banner): array
    {
        if ($banner === []) {
            return [];
        }

        $position = $this->text($banner['position'] ?? '');

        return [
            PluginSetting::ACTIVE => $this->isActive($options, $banner) ? '1' : '',
            ConsentSetting::TEXT => $this->text($banner['message_optin'] ?? ''),
            ConsentSetting::ACCEPT_BUTTON_TEXT => $this->text($banner['accept'] ?? ''),
            ConsentSetting::REJECT_BUTTON_TEXT => $this->text($banner['dismiss'] ?? ''),
            ConsentSetting::PREFERENCES_BUTTON_TEXT => $this->text($banner['view_preferences'] ?? ''),
            ConsentSetting::SAVE_BUTTON_TEXT => $this->text($banner['save_preferences'] ?? ''),
            ConsentSetting::POSITION => $this->text($banner['soft_cookiewall'] ?? '') !== ''
                ? self::POSITIONS['center']
                : self::POSITIONS[$position] ?? '',
            ConsentSetting::LOGO => $this->logo($banner),
            ConsentSetting::BACKGROUND_COLOR => $this->color($banner['colorpalette_background'] ?? []),
            ConsentSetting::TEXT_COLOR => $this->color($banner['colorpalette_text'] ?? []),
            ConsentSetting::CUSTOM_CSS => $this->customCss($banner),
            ConsentSetting::CATEGORIES => $this->categories($banner),
            ...$this->floatingButton($banner, $position),
        ];
    }

    /**
     * @param array<array-key, mixed> $options
     * @param array<string, mixed> $banner
     */
    private function isActive(array $options, array $banner): bool
    {
        return ($options['enable_cookie_banner'] ?? self::YES) === self::YES
            && $this->text($banner['disable_cookiebanner'] ?? '') === ''
            && \get_option('cmplz_wizard_completed_once') !== false;
    }

    /**
     * @param array<string, mixed> $banner
     */
    private function logo(array $banner): string
    {
        return match ($this->text($banner['use_logo'] ?? '')) {
            'custom' => $this->text($banner['logo_attachment_id'] ?? ''),
            'site' => $this->siteLogo(),
            default => '',
        };
    }

    /**
     * The logo of the theme, in its site identity.
     */
    private function siteLogo(): string
    {
        $logo = \get_theme_mod('custom_logo');

        return \is_numeric($logo) ? (string) (int) $logo : '';
    }

    private function color(mixed $palette): string
    {
        return $this->conversions->color(\is_array($palette) ? $palette['color'] ?? '' : '');
    }

    /**
     * @param array<string, mixed> $banner
     */
    private function customCss(array $banner): string
    {
        $css = $this->text($banner['custom_css'] ?? '');
        if ($this->text($banner['use_custom_cookie_css'] ?? '') === '' || \trim($css) === '') {
            return '';
        }

        return $this->conversions->commentedCss(self::NAME, $css);
    }

    /**
     * @param array<string, mixed> $banner
     * @return array<string, array{label: string, description: string}>
     */
    private function categories(array $banner): array
    {
        $categories = [];
        foreach (self::CATEGORIES as $category => [$label, $description]) {
            $texts = [
                'label' => $this->text($banner[$label] ?? ''),
                'description' => \wp_strip_all_tags($this->text($banner[$description] ?? '')),
            ];
            if ($texts['label'] === '' && $texts['description'] === '') {
                continue;
            }

            $categories[$category] = $texts;
        }

        return $categories;
    }

    /**
     * The button that opens the preferences after the choice, "Manage consent" in Complianz.
     *
     * @param array<string, mixed> $banner
     * @return array<string, string>
     */
    private function floatingButton(array $banner, string $position): array
    {
        if ($this->text($banner['manage_consent_options'] ?? '') === 'hide-everywhere') {
            return [];
        }

        return [
            ConsentSetting::FLOATING_BUTTON => '1',
            ConsentSetting::FLOATING_BUTTON_POSITION => $position === 'bottom-left' ? 'left' : 'right',
            ConsentSetting::FLOATING_BUTTON_LABEL => $this->text($banner['revoke'] ?? ''),
        ];
    }

    /**
     * The policy and the legal notice: an existing page, an address, or a page generated by Complianz.
     *
     * @param array<array-key, mixed> $options
     * @return array<string, string>
     */
    private function links(array $options): array
    {
        $links = [];
        foreach (self::DOCUMENTS as $document => $link) {
            $links = [...$links, ...$this->link($link, $this->documentTarget($document, $options[$document] ?? ''))];
        }

        return $links;
    }

    /**
     * @return array{page: int, url: string}
     */
    private function documentTarget(string $document, mixed $choice): array
    {
        return match ($choice) {
            'custom' => ['page' => $this->storage->documentPage($document), 'url' => ''],
            'generated' => ['page' => $this->storage->generatedDocumentPage($document), 'url' => ''],
            'url' => ['page' => 0, 'url' => $this->storage->documentUrl($document)],
            default => ['page' => 0, 'url' => ''],
        };
    }

    /**
     * @param array{page: int, url: string} $target
     * @return array<string, string>
     */
    private function link(BannerLink $link, array $target): array
    {
        $page = $this->conversions->page($target['page']);
        if ($page !== null) {
            return [
                $link->pageSetting() => $page['slug'],
                $link->urlSetting() => $page['url'],
                $link->textSetting() => $page['title'],
            ];
        }

        return $target['url'] !== '' ? [$link->urlSetting() => \esc_url_raw($target['url'])] : [];
    }

    /**
     * @param array<array-key, mixed> $options
     * @return array<string, string>
     */
    private function behaviour(array $options): array
    {
        $expiry = $options['cookie_expiry'] ?? null;

        return [
            ConsentSetting::CONSENT_DURATION => \is_numeric($expiry)
                ? $this->conversions->consentDuration((int) $expiry)
                : '',
            ConsentSetting::COOKIE_DOMAIN => $this->conversions->cookieDomain(
                $this->text($options['cookie_domain'] ?? '')
            ),
            ConsentSetting::GLOBAL_PRIVACY_CONTROL => $this->yes($options, 'respect_dnt'),
            ConsentSetting::EXCLUDED_PAGES => \implode(', ', $this->storage->excludedPosts()),
            BlockingSetting::VENDOR_CONSENT => $this->yes($options, 'consent_per_service'),
            BlockingSetting::PLACEHOLDER_TEXT => $this->placeholderText($options),
            BlockingSetting::PLACEHOLDER_BUTTON_TEXT => $this->text($options['agree_text_per_service'] ?? ''),
        ];
    }

    /**
     * The text of the blocked content, without the {category} placeholder of Complianz: the default of
     * Cookie Choices already names the category.
     *
     * @param array<array-key, mixed> $options
     */
    private function placeholderText(array $options): string
    {
        $text = $this->text($options['blocked_content_text'] ?? '');

        return \str_contains($text, '{category}') ? '' : $text;
    }

    /**
     * @param array<array-key, mixed> $options
     * @return array<string, string>
     */
    private function integrations(array $options): array
    {
        $consentMode = $this->yes($options, 'consent-mode');
        $configured = ($options['configuration_by_complianz'] ?? self::YES) === self::YES;
        $statistics = $this->text($options['compile_statistics'] ?? '');

        return [
            IntegrationSetting::CONSENT_MODE => $consentMode,
            IntegrationSetting::CONSENT_MODE_ADVANCED => $consentMode !== ''
                && $this->yes($options, 'gtag-basic-consent-mode') === '' ? '1' : '',
            IntegrationSetting::GA_MEASUREMENT_ID => $configured && \in_array($statistics, self::ANALYTICS, true)
                ? $this->tagId($options['ua_code'] ?? '', 'G-')
                : '',
            IntegrationSetting::GTM_CONTAINER_ID => $configured && $statistics === 'google-tag-manager'
                ? $this->tagId($options['gtm_code'] ?? '', 'GTM-')
                : '',
        ];
    }

    private function tagId(mixed $id, string $prefix): string
    {
        $id = \strtoupper(\trim($this->text($id)));

        return \str_starts_with($id, $prefix) ? $id : '';
    }

    /**
     * @param array<array-key, mixed> $options
     */
    private function yes(array $options, string $name): string
    {
        return ($options[$name] ?? '') === self::YES ? '1' : '';
    }

    /**
     * A text column, or the text of a text and checkbox column of Complianz.
     */
    private function text(mixed $value): string
    {
        if (\is_array($value)) {
            $value = $value['text'] ?? '';
        }

        return \is_scalar($value) ? \trim((string) $value) : '';
    }

    /**
     * @param array<string, mixed> $banner
     */
    private function isOn(array $banner, string $column): bool
    {
        return $this->text($banner[$column] ?? '') !== '';
    }

    /**
     * The regions where Complianz shows a banner, like eu and us.
     *
     * @param array<array-key, mixed> $options
     * @return list<string>
     */
    private function regions(array $options): array
    {
        $regions = $options['regions'] ?? [];
        $regions = \is_string($regions) ? [$regions] : $regions;

        return \array_values(\array_filter(\is_array($regions) ? $regions : [], \is_string(...)));
    }
}
