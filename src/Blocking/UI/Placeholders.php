<?php

declare(strict_types=1);

namespace ItalyCookieChoices\Blocking\UI;

use ItalyCookieChoices\Consent\UI\BuildingBanner;
use ItalyCookieChoices\Consent\UI\ConsentScript;
use ItalyCookieChoices\Consent\UI\ConsentTexts;
use ItalyCookieChoices\Settings\Options;
use ItalyStrap\Asset\AssetLoader;
use ItalyStrap\Asset\AssetStatus;
use ItalyStrap\Asset\BuildMetadata;
use ItalyStrap\Asset\BuildMetadataFile;
use ItalyStrap\Asset\Dependencies;
use ItalyStrap\Asset\EventName;
use ItalyStrap\Asset\Handle;
use ItalyStrap\Asset\Script;
use ItalyStrap\Asset\ScriptLoader;
use ItalyStrap\Asset\ScriptLoading;
use ItalyStrap\Asset\Style;
use ItalyStrap\Config\Config;
use ItalyStrap\Event\SubscriberInterface;
use ItalyStrap\View\ViewInterface;
use SplFileInfo;

/**
 * Loads the script that runs the blocked content after the consent, and prints a placeholder for each category.
 *
 * The script puts a copy of the placeholder before each blocked frame, its button accepts the category.
 */
final readonly class Placeholders implements SubscriberInterface
{
    public const HANDLE = 'italy-cookie-choices-blocking';

    private const SCRIPT = 'blocking.js';
    private const STYLE = 'blocking.css';
    private const TEMPLATE = 'placeholders';

    /**
     * @param string $buildPath The assets/build folder, with the trailing slash.
     * @param string $buildUrl The assets/build URL, with the trailing slash.
     */
    public function __construct(
        private ConsentTexts $texts,
        private Options $options,
        private BlockableRequest $request,
        private ViewInterface $view,
        private AssetLoader $assets,
        private ScriptLoader $scripts,
        private string $buildPath,
        private string $buildUrl,
    ) {
    }

    public function getSubscribedEvents(): iterable
    {
        yield EventName::FRONT_END => 'enqueue';
        yield 'wp_footer' => 'render';
    }

    public function enqueue(): void
    {
        $metadata = $this->metadata();
        if ($metadata === null || !$this->request->isBlockable()) {
            return;
        }

        $this->assets->load(
            new Script(
                handle: new Handle(self::HANDLE),
                source: $this->buildUrl . self::SCRIPT,
                dependencies: $metadata->dependencies()->with(new Dependencies(ConsentScript::HANDLE)),
                version: $metadata->version(),
                loading: new ScriptLoading(inFooter: true),
            ),
            new Style(
                handle: new Handle(self::HANDLE),
                source: $this->buildUrl . self::STYLE,
                version: $metadata->version(),
                data: ['rtl' => 'replace'],
            ),
        );
    }

    public function render(): void
    {
        if (!$this->scripts->is(new Handle(self::HANDLE), AssetStatus::Enqueued)) {
            return;
        }

        echo $this->view->render(self::TEMPLATE, new Config($this->data())); // phpcs:ignore -- Escaped in the template.
    }

    /**
     * The data the template prints, not escaped yet.
     *
     * @return array{
     *     preferences: string,
     *     categories: list<array{id: string, message: string, button: string}>
     * }
     */
    public function data(): array
    {
        $texts = $this->texts->all();
        $message = \wp_kses_post($this->options->translated('content_message_text'));
        $button = $this->options->translated('content_message_button_text');

        $categories = [];
        foreach ($texts['categories'] as $category) {
            if ($category['required']) {
                continue;
            }

            $categories[] = [
                'id' => $category['id'],
                'message' => $message !== '' ? $message : \esc_html(\sprintf(
                    /* translators: %s: the category label, like Marketing. */
                    \__('This content is blocked until you accept the %s cookies.', 'italy-cookie-choices'),
                    $category['label']
                )),
                'button' => $button !== '' ? $button : \sprintf(
                    /* translators: %s: the category label, like Marketing. */
                    \__('Accept the %s cookies', 'italy-cookie-choices'),
                    $category['label']
                ),
            ];
        }

        return [
            'preferences' => $texts['texts'][BuildingBanner::PREFERENCES] ?? '',
            'categories' => $categories,
        ];
    }

    /**
     * The dependencies and the version generated by the build, null when the assets are not built.
     */
    private function metadata(): ?BuildMetadata
    {
        $file = new BuildMetadataFile(new SplFileInfo($this->buildPath . self::SCRIPT));

        return $file->exists() ? $file->read() : null;
    }
}
